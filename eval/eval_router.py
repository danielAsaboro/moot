"""Router eval: which read-only tool does an ordinary question reach, by keyword rules and by a model's tool call?

Questions (eval/router/questions.json, frozen 2026-10-21 before any model saw them):
  misrouted  22 ordinary questions the keyword rules in moot/answer.py get wrong ("Who owns billing?")
  control    the 19 questions the rules already route (tests/test_answer.py), so a model that breaks them shows up

A pick is right when the tool matches and its input equals one of the accepted inputs exactly. The model sees only the
question, the tool list and a catalogue of ids read from the graph (answer._catalogue); an id outside it is rejected and
the rules answer, so "model" below is what a user gets: the model's pick, or the rules when the model's pick is refused.

  python3 eval/eval_router.py           replay the recorded replies in eval/router/llm_cache.jsonl (offline, CI)
  python3 eval/eval_router.py --live    call the model (Groq, moot/llm.py) for any question not yet recorded, and record it

Writes eval/results_router.md and eval/results_router.json (read by `moot verify`), with tokens, dollars and latency.
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
LIVE = "--live" in sys.argv
os.environ["MOOT_LLM_CACHE"] = str(ROOT / "eval" / "router" / "llm_cache.jsonl")
if LIVE:
    os.environ.pop("MOOT_LLM_REPLAY", None)
    os.environ["MOOT_LLM"] = "groq"
    os.environ["MOOT_LLM_PATIENT"] = "1"
else:
    os.environ["MOOT_LLM_REPLAY"] = "1"
    os.environ["MOOT_LLM"] = "groq"

from moot import answer, llm  # noqa: E402
from moot.graph import connect, seed  # noqa: E402
from moot.stats import wilson  # noqa: E402

OUT = Path(os.getenv("MOOT_EVAL_OUT") or ROOT / "eval")
Q = json.loads((ROOT / "eval" / "router" / "questions.json").read_text())


def right(pick: dict, item: dict) -> bool:
    return pick.get("tool") == item["tool"] and pick.get("input") in item["accept"]


def main() -> None:
    g = connect().select_graph("moot_eval_router")
    seed(g, None, fresh=True)
    rows = []
    try:
        for split in ("misrouted", "control"):
            for item in Q[split]:
                rules = answer.route(g, item["q"], Q["as_of"])
                model = answer.route_model(g, item["q"], Q["as_of"])
                used = model or rules
                meta = (model or {}).get("model")
                if meta:  # the same row whether the reply was just made or replayed from the recording
                    meta = {k: v for k, v in meta.items() if k != "cached"}
                    meta["usd"] = round(llm.price(meta["name"], meta["tokens_in"], meta["tokens_out"]), 6)
                rows.append(dict(split=split, q=item["q"], want=dict(tool=item["tool"], accept=item["accept"]),
                                 rules=dict(tool=rules["tool"], input=rules["input"], right=right(rules, item)),
                                 model=dict(tool=used["tool"], input=used["input"], right=right(used, item),
                                            by="model" if model else "rules", meta=meta)))
    finally:
        g.delete()
    summary = {}
    for split in ("misrouted", "control"):
        rs = [r for r in rows if r["split"] == split]
        metas = [r["model"]["meta"] for r in rs if r["model"]["meta"]]
        summary[split] = dict(
            n=len(rs), rules=sum(r["rules"]["right"] for r in rs), model=sum(r["model"]["right"] for r in rs),
            model_refused=sum(r["model"]["by"] == "rules" for r in rs),
            rules_ci=wilson(sum(r["rules"]["right"] for r in rs), len(rs)), model_ci=wilson(sum(r["model"]["right"] for r in rs), len(rs)),
            tokens_in=sum(m["tokens_in"] for m in metas), tokens_out=sum(m["tokens_out"] for m in metas),
            usd=round(sum(llm.price(m["name"], m["tokens_in"], m["tokens_out"]) for m in metas), 6),
            ms_median=sorted(m["ms"] for m in metas)[len(metas) // 2] if metas else None)
    models = sorted({r["model"]["meta"]["name"] for r in rows if r["model"]["meta"]})
    (OUT / "results_router.json").write_text(json.dumps(dict(summary=summary, models=models, rows=rows), indent=1))
    m, c = summary["misrouted"], summary["control"]
    lines = [
        "# Router: which tool does an ordinary question reach?", "",
        "Generated by `eval/eval_router.py` from `eval/router/questions.json` (frozen 2026-10-21, labelled before any model ran)"
        " and the recorded replies in `eval/router/llm_cache.jsonl`. Model: " + (", ".join(models) or "none recorded") + " on Groq, temperature 0.", "",
        "| questions | n | keyword rules | model tool call (rules when refused) | refused | tokens in / out | cost | median latency |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for name, s in (("rules misroute them", m), ("rules already route them", c)):
        lines.append(f"| {name} | {s['n']} | {s['rules']}/{s['n']} [{s['rules_ci'][0]:.2f}, {s['rules_ci'][1]:.2f}] | "
                     f"**{s['model']}/{s['n']}** [{s['model_ci'][0]:.2f}, {s['model_ci'][1]:.2f}] | {s['model_refused']} | "
                     f"{s['tokens_in']:,} / {s['tokens_out']:,} | ${s['usd']:.4f} | {s['ms_median']} ms |")
    lines += ["", "Brackets are 95% Wilson intervals. The misrouted set was chosen *because* the rules fail it, so the rules' 0 is by"
              " construction; it measures what a tool call adds, not how often the rules fail in use.", "",
              "| set | question | wanted | rules | model |", "|---|---|---|---|---|"]
    fmt = lambda t, i: f"`{t}` {json.dumps(i) if i else ''}".strip() if t else "nothing"
    for r in rows:
        mk = lambda x: ("✓ " if x["right"] else "✗ ") + fmt(x["tool"], x["input"])
        lines.append(f"| {r['split']} | {r['q']} | {fmt(r['want']['tool'], r['want']['accept'][0])} | {mk(r['rules'])} | "
                     f"{mk(r['model'])}{' (rules)' if r['model']['by'] == 'rules' else ''} |")
    (OUT / "results_router.md").write_text("\n".join(lines) + "\n")
    print(f"misrouted: rules {m['rules']}/{m['n']}, model {m['model']}/{m['n']}; control: rules {c['rules']}/{c['n']}, model {c['model']}/{c['n']}; "
          f"${m['usd'] + c['usd']:.4f}")


if __name__ == "__main__":
    main()
